"""Bundles the scripts in Scripts/ into app/js/samples.js.

The app then has its tutorial and guide even when index.html is opened straight
from disk, without the launcher. Run after editing anything in Scripts/:

    python build.py
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCRIPTS = HERE / "Scripts"
# Only these files are bundled, so a private script left in Scripts/ never ends up in the app.
SAMPLES = ("00 Start here.txt", "01 Tutorial.txt", "02 Phone tutorial.txt")
OUTPUT = HERE / "app" / "js" / "samples.js"


def render():
    """The contents of samples.js, built from the sample scripts."""
    samples = [
        {"name": re.sub(r"\.(txt|md)$", "", name, flags=re.I), "text": (SCRIPTS / name).read_text(encoding="utf-8-sig")}
        for name in SAMPLES
    ]
    # json.dumps escapes quotes and control characters. Escaping "<" as well means the
    # text can never close a script tag, however the file is loaded.
    payload = json.dumps(samples, ensure_ascii=False, indent=2).replace("<", "\\u003c")
    return "/* Generated by build.py from the files in Scripts/. Edit those, not this. */\n" f"window.Plexo.samples = {payload};\n"


def main():
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(HERE)} with: {', '.join(SAMPLES)}")


if __name__ == "__main__":
    main()
